package model;

public class Pj extends Funcionario{
	private int qtd_projetos;
	private double valor_projeto;
	private double irpf;
	
	public int getQtd_projetos() {
		return qtd_projetos;
	}
	public void setQtd_projetos(int qtd_projetos) {
		this.qtd_projetos = qtd_projetos;
	}
	public double getValor_projeto() {
		return valor_projeto;
	}
	public void setValor_projeto(double valor_projeto) {
		this.valor_projeto = valor_projeto;
	}
	public double getIrpf() {
		return irpf;
	}
	public void setIrpf(double irpf) {
		this.irpf = irpf;
	}
	
	
}
